/**
 * @fileoverview SEO - Search Engine Optimization component for meta tags and structured data
 * @module components/layout/SEO
 * 
 * @description
 * Manages all meta tags, Open Graph, Twitter Cards, and Schema.org structured data
 * for optimal search engine visibility and social media sharing across the ecosystem.
 * 
 * This component is critical for:
 * - Search engine rankings and rich snippets
 * - Social media sharing previews
 * - AI/LLM understanding via structured data
 * - Canonical URL management
 * - Google Knowledge Graph integration
 * 
 * @architecture
 * ```
 * Proto Configs (domain.proto, seo.proto)
 *         ↓
 * gatsby-config.ts (site metadata)
 *         ↓
 *    GraphQL Query
 *         ↓
 *    SEO Component (this)
 *         ├── useStaticQuery() → site metadata
 *         ├── useSchema() → Schema.org generation
 *         └── Helmet → <head> tags
 *              ├── Meta tags
 *              ├── Open Graph
 *              ├── Twitter Cards
 *              └── JSON-LD
 * ```
 * 
 * @proto-integration
 * Maps to multiple proto configurations:
 * 
 * - **SEOInfo** (seo.proto)
 *   - `meta_title`: Page title template
 *   - `meta_description`: Default description
 *   - `meta_keywords`: Default keywords
 *   - `og_image`: Open Graph image
 *   - `twitter_handle`: Twitter creator
 *   - `canonical_url`: Canonical URL pattern
 * 
 * - **DomainConfig** (domain.proto)
 *   - `domain_info.site_name`: Site title
 *   - `domain_info.tagline`: Site description
 *   - `domain_info.site_url`: Base URL for canonicals
 *   - `seo_defaults`: Default SEO settings
 * 
 * - **ArticleConfig** (blog.proto)
 *   - `title`: Article title
 *   - `excerpt`: Meta description
 *   - `tags`: Keywords
 *   - `cover_image`: OG image
 *   - `author`: Article author
 *   - `published_date`: datePublished
 *   - `updated_date`: dateModified
 * 
 * - **SchemaOrgConfig** (schema.proto)
 *   - `global_settings`: Organization/WebSite schema
 *   - `entity_mappings`: 300+ proto-to-Schema.org mappings
 *   - `article_defaults`: Article schema template
 *   - `validation`: Schema validation rules
 * 
 * @hook-integration
 * Primary hook consumer:
 * 
 * - **useSchema()** (`/src/hooks/useSchema.ts`)
 *   - `getBaseSchema()`: WebSite/Organization base
 *   - `buildArticleSchema()`: Article structured data
 *   - `mergeSchemas()`: Combine multiple schemas
 *   - `renderJsonLd()`: Generate script tag
 *   - Proto mappings: Automatic type resolution
 * 
 * @ecosystem-integration
 * - **Used by**: Layout, PageLayout, and all page components
 * - **Data flow**: gatsby-config → GraphQL → SEO component → <head> tags
 * - **Site metadata**: Generated by wrapper.sh from domain config
 * - **Schema.org**: Merged from base + page-specific schemas
 * - **GTM Integration**: Structured data events for analytics
 * - **Search Console**: Rich results validation
 * 
 * @configuration
 * - **Site metadata**: From `build/configs/[domain]/[mode]/config.yml`
 * - **Environment**: Variables set by wrapper.sh during build
 * - **Schema mappings**: 300+ proto-to-Schema.org mappings
 * - **Open Graph**: Default images in `static/og-image.png`
 * - **Twitter**: Creator handle from social config
 * 
 * @build-time
 * - **Site metadata**: Populated in gatsby-config.ts from proto
 * - **Schema generation**: gatsby-node.js with proto mappings
 * - **Canonical URLs**: Built from siteUrl + pathname
 * - **OG Images**: Optimized during build (1200x630)
 * 
 * @seo-features
 * - **Title formatting**: Page title | Site title (60 chars max)
 * - **Description**: Max 160 chars for optimal SERP display
 * - **Keywords**: 3-5 relevant terms (low weight but included)
 * - **Open Graph**: Facebook, LinkedIn, Discord sharing
 * - **Twitter Cards**: summary_large_image format
 * - **Schema.org**: WebSite, Article, Organization types
 * - **Canonical URLs**: Prevent duplicate content issues
 * 
 * @dos
 * - Always provide title and description
 * - Use pathname for proper canonical URLs
 * - Include article dates for blog posts
 * - Pass custom schema for special pages
 * - Keep descriptions under 160 characters
 * 
 * @donts
 * - Don't skip pathname (breaks canonicals)
 * - Don't use more than 5 keywords
 * - Don't duplicate schema data
 * - Don't use relative image URLs
 * - Don't forget article prop for blog posts
 * 
 * @example
 * ```tsx
 * // Service page with custom schema
 * <SEO
 *   title="AI Transformation Services"
 *   description="Enterprise AI consulting and implementation"
 *   pathname="/services"
 *   schema={servicePageSchema}
 *   keywords={['AI', 'transformation', 'consulting']}
 * />
 * 
 * // Blog article with full metadata
 * <SEO
 *   title={article.title}
 *   description={article.excerpt}
 *   pathname={`/blog/${article.slug}`}
 *   article={true}
 *   image={article.cover_image}
 *   datePublished={article.published_date}
 *   dateModified={article.updated_date}
 *   author={article.author}
 *   contentType="TechnicalArticle"
 * />
 * 
 * // Landing page with custom OG image
 * <SEO
 *   title="getHarsh - AI Transformation Expert"
 *   description="Building the future with AI"
 *   pathname="/"
 *   image="/og-image-home.png"
 * />
 * ```
 * 
 * @see {@link file://./BUILD.md#seo-configuration} - SEO build settings
 * @see {@link file://./CMS.md#seo-fields} - CMS SEO configuration
 * @see {@link file://./SEARCH.md#structured-data} - Schema.org strategy
 * @see {@link file://../../hooks/useSchema.ts} - Schema generation hook
 * @see {@link file://./Layout.tsx} - Primary consumer component
 * 
 * @since 1.0.0
 */

import React from 'react'
import { Helmet } from 'react-helmet'
import { useStaticQuery, graphql } from 'gatsby'
import { useSchema } from '@/hooks/useSchema'

/**
 * @interface SEOProps
 * @description Props for SEO component with comprehensive metadata options
 * 
 * All props are optional to allow flexible usage, but title and description
 * are strongly recommended for optimal SEO performance.
 * 
 * @property {string} [title] - Page-specific title (will be appended with site title)
 * Should be 50-60 characters for optimal display in search results.
 * Maps to ArticleConfig.title or PageConfig.title in proto.
 * 
 * @property {string} [description] - Meta description for search engines
 * Keep under 160 characters for full display in SERPs.
 * Maps to ArticleConfig.excerpt or SEOInfo.meta_description.
 * 
 * @property {string[]} [keywords] - SEO keywords array (use sparingly, 3-5 max)
 * Low SEO weight but useful for content categorization.
 * Maps to ArticleConfig.tags or SEOInfo.meta_keywords.
 * 
 * @property {boolean} [article=false] - Whether this is an article page
 * Determines Schema.org type (Article vs WebPage) and Open Graph type.
 * Set to true for blog posts, news, and documentation pages.
 * 
 * @property {string} [pathname=''] - Current page pathname for canonical URL
 * Critical for preventing duplicate content issues. Should start with /.
 * Combined with siteUrl to create full canonical URL.
 * 
 * @property {string} [image] - Open Graph image URL (defaults to site OG image)
 * Should be 1200x630px for optimal display. Can be relative or absolute.
 * Maps to ArticleConfig.cover_image or SEOInfo.og_image.
 * 
 * @property {any} [schema] - Custom Schema.org structured data to merge
 * Generated by gatsby-node.js using proto-to-Schema.org mappings.
 * Merged with base schema (WebSite/Organization) or article schema.
 * 
 * @property {string} [datePublished] - Article publish date (ISO string)
 * Required for article schema. Maps to ArticleConfig.published_date.
 * Format: "2024-01-15T10:00:00Z"
 * 
 * @property {string} [dateModified] - Article modification date (ISO string)
 * Indicates content freshness to search engines.
 * Maps to ArticleConfig.updated_date.
 * 
 * @property {string} [contentType] - Content type enum for schema mapping
 * Enables proper Schema.org type selection (e.g., "TechnicalArticle").
 * Maps to ArticleConfig.type or ContentTypeMapping in proto.
 * 
 * @property {string | object} [author] - Article author information
 * Can be string (name) or object with name and url.
 * Maps to ArticleConfig.author or AuthorConfig in proto.
 * 
 * @example
 * ```tsx
 * const seoProps: SEOProps = {
 *   title: "Understanding React Hooks",
 *   description: "A comprehensive guide to React Hooks",
 *   keywords: ["React", "Hooks", "JavaScript"],
 *   article: true,
 *   pathname: "/blog/react-hooks",
 *   image: "/images/react-hooks-cover.jpg",
 *   datePublished: "2024-01-15T10:00:00Z",
 *   author: { name: "Harsh Gupta", url: "https://getharsh.com" },
 *   contentType: "TechnicalArticle"
 * }
 * ```
 */
interface SEOProps {
  /** Page-specific title (will be appended with site title) */
  title?: string
  /** Meta description for search engines (max 160 chars recommended) */
  description?: string
  /** SEO keywords array (use sparingly, 3-5 max) */
  keywords?: string[]
  /** Whether this is an article page (affects Schema.org type) */
  article?: boolean
  /** Current page pathname for canonical URL generation */
  pathname?: string
  /** Open Graph image URL (defaults to site OG image) */
  image?: string
  /** Custom Schema.org structured data to merge with base schema */
  schema?: any
  /** Article publish date (ISO string) */
  datePublished?: string
  /** Article modification date (ISO string) */
  dateModified?: string
  /** Content type enum value for schema mapping */
  contentType?: string
  /** Author name or object */
  author?: string | { name: string; url?: string }
}

/**
 * SEO component - Generates comprehensive meta tags and structured data
 * 
 * Core component for managing all SEO-related tags in the document head.
 * Integrates with Gatsby's static query system to fetch site metadata and
 * uses the useSchema hook for structured data generation.
 * 
 * The component follows a three-layer approach:
 * 1. **Site Metadata**: Base configuration from gatsby-config
 * 2. **Page Props**: Page-specific overrides passed as props
 * 3. **Schema Generation**: Dynamic structured data based on content type
 * 
 * @component
 * @param {SEOProps} props - SEO configuration object
 * @param {string} [props.title] - Page title (appended with site title)
 * @param {string} [props.description] - Meta description (160 chars max)
 * @param {string[]} [props.keywords] - SEO keywords (3-5 recommended)
 * @param {boolean} [props.article=false] - Whether page is an article
 * @param {string} [props.pathname=''] - Page path for canonical URL
 * @param {string} [props.image] - Open Graph image URL
 * @param {any} [props.schema] - Custom Schema.org structured data
 * @param {string} [props.datePublished] - Article publish date (ISO)
 * @param {string} [props.dateModified] - Article modification date (ISO)
 * @param {string} [props.contentType] - Content type for schema mapping
 * @param {string|object} [props.author] - Article author information
 * 
 * @returns {JSX.Element} Helmet component containing:
 * - Basic meta tags (title, description, keywords)
 * - Open Graph tags for social sharing
 * - Twitter Card tags for Twitter sharing
 * - Schema.org JSON-LD structured data
 * 
 * @remarks
 * The component uses React Helmet for managing document head tags,
 * ensuring proper server-side rendering with Gatsby. All tags are
 * deduplicated and properly escaped.
 * 
 * GraphQL Query:
 * - Fetches site metadata from gatsby-config.ts
 * - Data populated by wrapper.sh from proto configs
 * - Includes title, description, siteUrl, author, social
 * 
 * Schema Generation:
 * - Uses useSchema hook for proto-aware generation
 * - Automatically maps content types to Schema.org types
 * - Merges base, article, and custom schemas
 * 
 * @example
 * ```tsx
 * // Basic page SEO
 * <SEO
 *   title="About Us"
 *   description="Learn about our mission"
 *   pathname="/about"
 * />
 * 
 * // Article with full metadata
 * <SEO
 *   title={post.title}
 *   description={post.excerpt}
 *   article={true}
 *   pathname={`/blog/${post.slug}`}
 *   image={post.coverImage}
 *   datePublished={post.date}
 *   author={post.author}
 * />
 * ```
 */
export const SEO: React.FC<SEOProps> = ({
  title,
  description,
  keywords = [],
  article = false,
  pathname = '',
  image,
  schema,
  datePublished,
  dateModified,
  contentType,
  author
}) => {
  // Query site metadata from gatsby-config (populated by wrapper.sh)
  const { site } = useStaticQuery(graphql`
    query SEOQuery {
      site {
        siteMetadata {
          title
          description
          siteUrl
          author
          social {
            twitter
          }
        }
      }
    }
  `)

  const siteMetadata = site.siteMetadata
  
  // Get schema utilities from hook
  const { 
    getBaseSchema, 
    buildArticleSchema, 
    mergeSchemas, 
    renderJsonLd 
  } = useSchema()
  
  // Construct SEO values with fallbacks
  const seo = {
    title: title ? `${title} | ${siteMetadata.title}` : siteMetadata.title,
    description: description || siteMetadata.description,
    url: `${siteMetadata.siteUrl}${pathname}`,
    image: image || `${siteMetadata.siteUrl}/og-image.png`,
  }

  // Build appropriate schema based on page type
  let pageSchema
  if (article) {
    // Build article schema for blog posts with proper mapping support
    pageSchema = buildArticleSchema({
      title: title || siteMetadata.title,
      description: seo.description,
      datePublished: datePublished || new Date().toISOString(),
      dateModified: dateModified,
      author: author || siteMetadata.author,
      url: seo.url,
      image: seo.image,
      contentType: contentType // This enables proper Schema.org type mapping
    })
  } else {
    // Use base schema for regular pages
    pageSchema = getBaseSchema()
  }

  // Merge with custom schema from pages (e.g., services, projects)
  // Custom schema generated in gatsby-node.js with proto-to-Schema.org mappings
  const finalSchema = schema ? mergeSchemas(pageSchema, schema) : pageSchema

  return (
    <Helmet>
      {/* Basic Meta Tags */}
      <title>{seo.title}</title>
      <meta name="description" content={seo.description} />
      {keywords.length > 0 && (
        <meta name="keywords" content={keywords.join(', ')} />
      )}

      {/* Open Graph */}
      <meta property="og:title" content={seo.title} />
      <meta property="og:description" content={seo.description} />
      <meta property="og:type" content={article ? 'article' : 'website'} />
      <meta property="og:url" content={seo.url} />
      <meta property="og:image" content={seo.image} />

      {/* Twitter Card */}
      <meta name="twitter:card" content="summary_large_image" />
      {siteMetadata.social?.twitter && (
        <meta name="twitter:creator" content={`@${siteMetadata.social.twitter}`} />
      )}
      <meta name="twitter:title" content={seo.title} />
      <meta name="twitter:description" content={seo.description} />
      <meta name="twitter:image" content={seo.image} />

      {/* Schema.org JSON-LD - Using centralized hook */}
      {renderJsonLd(finalSchema)}
    </Helmet>
  )
}