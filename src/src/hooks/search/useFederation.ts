/**
 * @fileoverview Cross-Domain Search Federation Hook
 * @module hooks/search/useFederation
 * 
 * @description
 * Enables cross-domain search federation across the getHarsh ecosystem.
 * This hook aggregates search results from multiple domains (blog.*, project.*)
 * to provide unified discovery of content across all ecosystem properties.
 * 
 * Federation allows users to find relevant content regardless of which domain
 * they're currently on, improving content discovery and cross-pollination
 * between blogs, projects, and documentation sites.
 * 
 * @architecture
 * The federation system works as follows:
 * 1. Each domain publishes a federated-manifest.json with search endpoints
 * 2. This hook loads the manifest and discovers available domains
 * 3. When searching, parallel requests are sent to all federated domains
 * 4. Results are aggregated, deduplicated, and ranked
 * 5. Domain attribution is maintained for proper linking
 * 
 * @ecosystem-integration
 * - Manifest: Generated by build process from discovery data
 * - Search endpoints: Each domain exposes /search-index.json
 * - Cross-domain: Works across blog.*, project.*, docs.* subdomains
 * - Analytics: Tracks federation usage for optimization
 * - Performance: Parallel requests with configurable timeout
 * 
 * @federation-protocol
 * Each federated domain must:
 * - Publish a search index at /search-index.json
 * - Include domain metadata in the manifest
 * - Support CORS for cross-origin requests
 * - Return results in the standard SearchDocument format
 * 
 * @performance
 * - Parallel requests: All domains searched simultaneously
 * - Timeout: Default 5s per domain to prevent blocking
 * - Caching: Results cached for query deduplication
 * - Deduplication: Prevents duplicate results across domains
 * - Limit: Default 3 results per domain to prevent overwhelming
 * 
 * @dos
 * - Use federation for cross-domain discovery
 * - Configure appropriate timeouts for your network
 * - Handle errors gracefully per domain
 * - Track federation performance metrics
 * - Deduplicate results by ID or URL
 * 
 * @donts
 * - Don't federate sensitive or private content
 * - Don't rely on federation for primary search
 * - Don't ignore CORS configuration
 * - Don't skip error handling
 * - Don't federate without user consent
 * 
 * @example
 * ```tsx
 * const { searchFederated, federatedResults, isLoading } = useFederation({
 *   timeout: 3000,
 *   maxResultsPerDomain: 5
 * })
 * 
 * const handleSearch = async (query: string) => {
 *   const results = await searchFederated(query)
 *   // Results from all federated domains
 * }
 * ```
 * 
 * @see {@link file://./SEARCH.md#cross-domain-federation} - Federation architecture
 * @see {@link file://./BUILD.md#federation-manifest} - Manifest generation
 * @see {@link file://./config/discovery-manifest.json} - Discovery data
 * @see {@link file://./src/hooks/search/useFlexSearch.ts} - Primary search
 * @see {@link file://./src/components/search/FederatedSearch.tsx} - UI component
 * 
 * @since 2.0.0
 */

import { useState, useEffect, useCallback } from 'react'
import { useSearchTracking } from './useSearchTracking'

/**
 * Federated domain configuration.
 * Describes a searchable domain in the ecosystem.
 */
interface FederatedDomain {
  domain: string
  type: string
  relationship?: string
  searchEndpoint: string
  capabilities?: {
    filters?: boolean
    fuzzy?: boolean
    suggestions?: boolean
  }
}

/**
 * Federation manifest structure.
 * Published by each domain to enable discovery.
 */
interface FederationManifest {
  version: string
  currentDomain: {
    domain: string
    type: string
    searchEndpoint: string
    capabilities?: Record<string, boolean>
  }
  federation: {
    domains: FederatedDomain[]
  }
}

/**
 * Result from a federated domain search.
 * Includes domain attribution and error handling.
 */
interface FederatedResult {
  domain: string
  results: any[]
  error?: string
}

/**
 * Federation configuration options.
 * Customize timeout, result limits, and error handling.
 */
interface UseFederationOptions {
  manifestPath?: string
  maxResultsPerDomain?: number
  timeout?: number
  onError?: (domain: string, error: Error) => void
}

/**
 * Cross-domain search federation hook.
 * Aggregates search results from multiple ecosystem domains.
 * 
 * @param {UseFederationOptions} options - Federation configuration
 * @returns Federation search methods and state
 * 
 * @example
 * ```tsx
 * const federation = useFederation({
 *   timeout: 3000,
 *   onError: (domain, error) => console.error(`${domain} failed:`, error)
 * })
 * ```
 */
export function useFederation(options?: UseFederationOptions) {
  const [manifest, setManifest] = useState<FederationManifest | null>(null)
  const [isLoading, setIsLoading] = useState(false)
  const [federatedResults, setFederatedResults] = useState<FederatedResult[]>([])
  const { trackFederationSearch } = useSearchTracking()

  const manifestPath = options?.manifestPath || '/federated-manifest.json'
  const maxResults = options?.maxResultsPerDomain || 3
  const timeout = options?.timeout || 5000

  // Load federation manifest
  useEffect(() => {
    const loadManifest = async () => {
      try {
        const response = await fetch(manifestPath)
        if (response.ok) {
          const data = await response.json()
          setManifest(data)
        }
      } catch (error) {
        console.warn('Failed to load federation manifest:', error)
      }
    }

    loadManifest()
  }, [manifestPath])

  /**
   * Search a single federated domain.
   * Handles timeouts and errors gracefully.
   * 
   * @param domain - Domain configuration
   * @param query - Search query
   * @returns Results from the domain or error
   */
  const searchFederatedDomain = useCallback(async (
    domain: FederatedDomain,
    query: string
  ): Promise<FederatedResult> => {
    try {
      const controller = new AbortController()
      const timeoutId = setTimeout(() => controller.abort(), timeout)

      const response = await fetch(domain.searchEndpoint, {
        signal: controller.signal,
        headers: {
          'Accept': 'application/json'
        }
      })

      clearTimeout(timeoutId)

      if (!response.ok) {
        throw new Error(`HTTP ${response.status}`)
      }

      const indexData = await response.json()
      
      // Perform search on the remote index
      // This is simplified - in reality you'd use the remote search API
      const results = indexData.documents?.filter((doc: any) => {
        const searchableText = [
          doc.title,
          doc.summary,
          doc.content,
          ...(doc.tags || []),
          ...(doc.keywords || [])
        ].join(' ').toLowerCase()
        
        return searchableText.includes(query.toLowerCase())
      }).slice(0, maxResults) || []

      trackFederationSearch(domain.domain, results.length)

      return {
        domain: domain.domain,
        results
      }
    } catch (error) {
      const errorMessage = error instanceof Error ? error.message : 'Unknown error'
      options?.onError?.(domain.domain, error as Error)
      
      return {
        domain: domain.domain,
        results: [],
        error: errorMessage
      }
    }
  }, [maxResults, timeout, trackFederationSearch, options])

  /**
   * Search all federated domains in parallel.
   * Aggregates and deduplicates results.
   * 
   * @param query - Search query
   * @returns Aggregated results from all domains
   */
  const searchFederated = useCallback(async (query: string) => {
    if (!manifest?.federation?.domains || query.length < 2) {
      setFederatedResults([])
      return []
    }

    setIsLoading(true)

    try {
      // Search all federated domains in parallel
      const searchPromises = manifest.federation.domains.map(domain =>
        searchFederatedDomain(domain, query)
      )

      const results = await Promise.all(searchPromises)
      setFederatedResults(results)
      
      return results
    } catch (error) {
      console.error('Federation search error:', error)
      setFederatedResults([])
      return []
    } finally {
      setIsLoading(false)
    }
  }, [manifest, searchFederatedDomain])

  /**
   * Clear all federated search results.
   * Used when resetting search state.
   */
  const clearFederatedResults = useCallback(() => {
    setFederatedResults([])
  }, [])

  /**
   * Merge and deduplicate results from all domains.
   * Maintains domain attribution for proper linking.
   * 
   * @returns Deduplicated array of all results
   */
  const getMergedResults = useCallback(() => {
    const merged: any[] = []
    const seen = new Set<string>()

    federatedResults.forEach(domainResult => {
      domainResult.results.forEach(result => {
        // Add domain info to result
        const enrichedResult = {
          ...result,
          _federationDomain: domainResult.domain
        }

        // Deduplicate by ID or URL
        const key = result.id || result.url || result.slug
        if (key && !seen.has(key)) {
          seen.add(key)
          merged.push(enrichedResult)
        }
      })
    })

    return merged
  }, [federatedResults])

  return {
    manifest,
    isLoading,
    federatedResults,
    searchFederated,
    clearFederatedResults,
    getMergedResults,
    hasFederation: Boolean(manifest?.federation?.domains?.length)
  }
}